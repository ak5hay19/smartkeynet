"""
forecaster/dataset.py

Sliding-window supervised datasets for `forecaster/train.py` (PLAN.md
Addition A). Owned by Person A (split.md §1).

Built from logged environment rollouts: inputs are QBER, SKR, per-class
arrival counts, hybrid serves and pool level; targets are the same
signals shifted forward by each pool-head horizon H in {10, 25, 50}, and
the realised threat posture over the next k=5 steps.

Never build this dataset from `rl_experiment_*` / `synthetic_rl_*`
Q-OPSEC logs (PLAN.md "Datasets & Provenance": those are for baseline
reproduction + feedback calibration only). Training on the outputs of
the agent we are critiquing would be imitation-learning the exact
flawed policy the project exists to attack.

---------------------------------------------------------------------
Where the rollouts come from, and why it matters
---------------------------------------------------------------------
`collect_rollouts` drives the environment with **baseline policies**
(`agents/baselines.py`) across S1-S4 seeds, per Addition A: "Trained on
rollouts generated by baseline policies across S1-S4 seeds."

Not with the DQN, and the distinction is not pedantic. If the
forecaster were trained on the DQN's own trajectories, the two would
co-adapt: the agent would shape the data distribution the forecaster
learns from, the forecaster would shape the states the agent sees, and
the E-A ablation ("how much is anticipation worth?") would no longer
have a clean control. Baseline rollouts keep the forecaster's training
distribution fixed and independent of whatever the agent later becomes.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from typing import Any

import numpy as np
import torch

from agents.baselines import (
    AlwaysHybridPolicy,
    AlwaysPQCPolicy,
    GreedyRecommenderPolicy,
    RandomPolicy,
    StaticThresholdPolicy,
)
from env.contracts import ForecastObservation
from env.environment import SmartKeyNetEnv
from forecaster.model import HORIZONS, THREAT_HORIZON_STEPS, WINDOW, observation_to_features

TRAINING_SCENARIOS: tuple[str, ...] = ("S1", "S2", "S3", "S4")
"""Hard Rule 8: S5 and S6 are held out, so the forecaster never sees
them either. A forecaster trained on the migration timeline would leak
that timeline into the agent's state vector, which is exactly the
memorisation the held-out evaluation exists to prevent."""


@dataclass
class RolloutLog:
    """One episode's per-step signals, in step order."""

    features: list[list[float]] = field(default_factory=list)
    postures: list[int] = field(default_factory=list)
    pool_fill: list[float] = field(default_factory=list)
    skr: list[float] = field(default_factory=list)
    hybrid_mandatory_arrivals: list[int] = field(default_factory=list)

    def __len__(self) -> int:
        return len(self.features)


def _baseline_policies(config: dict[str, Any]) -> list[Any]:
    """The policy mix rollouts are collected under.

    Deliberately diverse: a forecaster trained only on a frugal policy
    would never observe a drained pool, and would therefore be worst
    exactly where its forecast matters most. Including the always-hybrid
    villain guarantees the low-pool region of the state space is
    represented.
    """
    max_key_age = float(config["key_lifetime"]["max_key_age_steps"])
    return [
        AlwaysPQCPolicy(),
        AlwaysHybridPolicy(),
        GreedyRecommenderPolicy(),
        StaticThresholdPolicy(0.3, 0, 0.7, max_key_age),
        StaticThresholdPolicy(0.7, 2, 0.9, max_key_age),
        RandomPolicy(seed=0),
    ]


def collect_rollouts(
    config: dict[str, Any],
    n_steps: int = 1500,
    seeds: Iterable[int] = (0, 1, 2),
    scenarios: Iterable[str] = TRAINING_SCENARIOS,
) -> list[RolloutLog]:
    """Drive baseline policies through the environment, logging the
    forecaster's inputs and the quantities its heads must predict."""
    logs: list[RolloutLog] = []

    for scenario in scenarios:
        for seed in seeds:
            for policy in _baseline_policies(config):
                env_config = {
                    **config,
                    "scenario": scenario,
                    "seed": seed,
                    "max_steps": n_steps,
                    "scenario_steps": n_steps,
                    # the forecaster must exist for the env to build
                    # ForecastObservations at all; EWMA is the cheap
                    # choice and its own outputs are not logged here
                    "use_foresight": "ewma",
                    # S4's flood targets a named tenant, which only the
                    # graph source has. Using it for every scenario also
                    # keeps the rollout distribution consistent across
                    # the four -- otherwise S4 samples would differ from
                    # S1-S3 in arrival structure as well as in the flood,
                    # and the forecaster would learn the difference
                    # between two request sources rather than between
                    # two scenarios.
                    "request_source": "graph",
                    # Real RT-IoT2022 flow features. The forecaster's threat
                    # head is a posture classifier, so it has to see what
                    # posture is actually defined by; trained on the synthetic
                    # placeholder it scored at chance.
                    "threat_source": config.get("threat_source", "rt_iot2022"),
                    "threat_split": "train",
                }
                env = SmartKeyNetEnv(env_config)
                state, info = env.reset(seed=seed)

                log = RolloutLog()
                for _ in range(n_steps):
                    mask = info["action_mask"]
                    observation: ForecastObservation = env._build_forecast_observation()

                    log.features.append(observation_to_features(observation))
                    # INSTANTANEOUS posture, not the ratcheted one.
                    # The ratchet is monotone and sticky, so a ratcheted
                    # label is "the same as now" in 99.9% of samples and
                    # the head collapses to the majority class however
                    # smooth the input is. The policy table applies the
                    # ratchet downstream; the forecaster's job is to see
                    # where the raw reading is heading so the table can
                    # ratchet *early*.
                    log.postures.append(int(env._current_posture))
                    log.pool_fill.append(float(observation["pool_fill"]))
                    log.skr.append(float(observation["skr"]))
                    log.hybrid_mandatory_arrivals.append(
                        1 if env._current_request["hybrid_mandatory"] else 0
                    )

                    action = policy.act(state, mask)
                    state, reward, terminated, truncated, info = env.step(action)
                    if truncated:
                        break

                if len(log) > WINDOW + max(HORIZONS):
                    logs.append(log)

    return logs


def build_datasets(
    logs: list[RolloutLog],
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Turn rollout logs into `(windows, threat_targets, pool_targets)`.

    Shapes:
      - `windows`        (n_samples, WINDOW, N_FEATURES)
      - `threat_targets` (n_samples, THREAT_HORIZON_STEPS)  -- class indices
      - `pool_targets`   (n_samples, 9)

    Pool targets, in the order `PoolForecast` declares:
      - `pool_level_hat[H]`     = pool fill at t+H
      - `skr_mean_hat[H]`       = mean SKR over (t, t+H]
      - `hybrid_demand_hat[H]`  = count of hybrid-mandatory arrivals in
        (t, t+H], normalised by H so the three horizons live on a
        comparable scale. (The EWMA fallback flat-holds a per-step rate
        instead of scaling by H -- documented there as an accepted
        fallback-only simplification. A trend-aware model should not
        replicate it, so this target is a genuine per-step rate the
        model can actually learn.)

    Windows are cut so that every target is fully observed: a sample at
    step `t` requires `t >= WINDOW - 1` and `t + max(HORIZONS) < len`.
    Truncated or partially-observed targets are dropped rather than
    padded, because a padded target teaches the model a value that never
    occurred.
    """
    window_rows: list[list[list[float]]] = []
    threat_rows: list[list[int]] = []
    pool_rows: list[list[float]] = []

    longest_horizon = max(HORIZONS)

    for log in logs:
        n = len(log)
        for t in range(WINDOW - 1, n - longest_horizon - 1):
            window_rows.append(log.features[t - WINDOW + 1 : t + 1])

            threat_rows.append([log.postures[t + k + 1] for k in range(THREAT_HORIZON_STEPS)])

            pool_target: list[float] = []
            for horizon in HORIZONS:
                pool_target.append(log.pool_fill[t + horizon])
            for horizon in HORIZONS:
                pool_target.append(float(np.mean(log.skr[t + 1 : t + horizon + 1])))
            for horizon in HORIZONS:
                arrivals = sum(log.hybrid_mandatory_arrivals[t + 1 : t + horizon + 1])
                pool_target.append(arrivals / horizon)
            pool_rows.append(pool_target)

    if not window_rows:
        raise ValueError(
            "no training samples produced -- rollouts must be longer than "
            f"WINDOW ({WINDOW}) + max horizon ({longest_horizon})"
        )

    return (
        torch.tensor(window_rows, dtype=torch.float32),
        torch.tensor(threat_rows, dtype=torch.long),
        torch.tensor(pool_rows, dtype=torch.float32),
    )


def chronological_split(
    logs: list[RolloutLog],
    train_fraction: float = 0.70,
    validation_fraction: float = 0.15,
) -> tuple[list[RolloutLog], list[RolloutLog], list[RolloutLog]]:
    """Split by WHOLE ROLLOUT: 70% of episodes train, 15% validation, 15%
    test -- satisfying SMARTKEYNET_BUILD_SPEC.md §S9 rule 3's purpose.

    WHY THIS REPLACED A SHUFFLED SPLIT (2026-08-18). The previous
    `train_validation_split` shuffled samples before splitting, on the
    reasoning that samples from one episode are correlated and a contiguous
    tail split would measure episode-level rather than step-level
    generalisation.

    That reasoning was wrong, and the spec names the mistake directly:
    "Random-window splitting leaks adjacent timesteps across the split and
    will make your LSTM look far better than it is. This is the single most
    common quiet mistake in time-series ML and a reviewer will ask."

    The leak is severe here because windows are W=64 wide and stride 1, so
    consecutive samples share 63 of 64 timesteps. A shuffled split puts
    near-duplicate windows on both sides, and the reported accuracy measures
    memorisation rather than forecasting.

    Splitting each rollout in time, with a `WINDOW + max(HORIZONS)` margin
    discarded at each boundary, means no training window overlaps any
    validation or test window at all.
    """
    # WHOLE ROLLOUTS, not time-slices within a rollout.
    #
    # The spec assumes rollouts are continuous streams, where slicing by time
    # is the right way to avoid leakage. These rollouts are not: each episode
    # replays a *scripted scenario* whose posture arc runs CALM -> ELEVATED ->
    # HIGH -> CALM at fixed steps. Slicing one episode by time therefore
    # splits the label distribution as well as the timeline -- measured, the
    # final 30% of every episode is post-attack CALM only, so validation and
    # test contained exactly ONE class and balanced accuracy read 0.500 by
    # construction.
    #
    # Partitioning whole episodes achieves what the spec's rule is *for* --
    # no window in one split shares a timestep with any window in another,
    # since they come from different episodes entirely -- while keeping the
    # full posture arc in every split. Episodes differ by seed, scenario and
    # baseline policy, so held-out episodes are genuinely unseen trajectories.
    ordered = list(logs)
    n_logs = len(ordered)
    train_end = int(n_logs * train_fraction)
    validation_end = int(n_logs * (train_fraction + validation_fraction))

    return (
        ordered[:train_end],
        ordered[train_end:validation_end],
        ordered[validation_end:],
    )


def persistence_baseline_mae(logs: list[RolloutLog]) -> float:
    """MAE of "the pool will be where it is now" on the pool-level targets.

    SMARTKEYNET_BUILD_SPEC.md §S9 test 7: the LSTM must beat this, or the
    honest move is to ship EWMA and say so. Pool level over these horizons is
    close to a random walk, and persistence is near-optimal for a random walk
    -- so this is a genuinely hard bar, not a formality.
    """
    _windows, _threat, pool_targets = build_datasets(logs)
    errors = []
    for log in logs:
        n = len(log)
        for t in range(WINDOW - 1, n - max(HORIZONS) - 1):
            current = log.pool_fill[t]
            for horizon in HORIZONS:
                errors.append(abs(log.pool_fill[t + horizon] - current))
    return float(np.mean(errors)) if errors else float("nan")


def train_validation_split(
    windows: torch.Tensor,
    threat_targets: torch.Tensor,
    pool_targets: torch.Tensor,
    validation_fraction: float = 0.2,
    seed: int = 0,
) -> tuple[tuple[torch.Tensor, ...], tuple[torch.Tensor, ...]]:
    """DEPRECATED shuffled split -- use `chronological_split` instead.

    Retained only so the reason it was wrong stays visible: shuffling
    W=64-wide stride-1 windows puts near-duplicates (63 of 64 timesteps
    shared) on both sides of the split, which measures memorisation rather
    than forecasting. See `chronological_split` and spec §S9 rule 3.
    """
    generator = torch.Generator().manual_seed(seed)
    permutation = torch.randperm(windows.shape[0], generator=generator)
    n_validation = max(1, int(windows.shape[0] * validation_fraction))

    validation_idx = permutation[:n_validation]
    train_idx = permutation[n_validation:]

    return (
        (windows[train_idx], threat_targets[train_idx], pool_targets[train_idx]),
        (windows[validation_idx], threat_targets[validation_idx], pool_targets[validation_idx]),
    )
